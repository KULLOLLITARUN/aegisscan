"""
FileClassifier — enriches a raw Path into a typed FileInfo.

Responsibilities:
  - Detect language by file extension
  - Detect binary files (null-byte probe)
  - Detect auto-generated files (lock files, minified JS, known gen-headers)
  - Flag oversized files (above MAX_FILE_SIZE_BYTES)
  - Count lines for text files that are neither binary nor oversized

Design rules (plan §2):
  - Pure classification layer: no Semgrep, Groq, security, or optimization logic.
  - No config.py in V0; thresholds are hardcoded constants here.
  - Every path exits as a FileInfo — never a raw dict.
"""
from __future__ import annotations

import logging
from pathlib import Path

from scanner.models.file_info import FileInfo

log = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Hardcoded defaults (no config.py in V0)
# ---------------------------------------------------------------------------

#: Files larger than this are flagged is_oversized and not read for line count.
MAX_FILE_SIZE_BYTES: int = 1 * 1024 * 1024  # 1 MB

#: How many bytes to probe for null bytes when detecting binary files.
_BINARY_PROBE_BYTES: int = 8192

# ---------------------------------------------------------------------------
# Language map  (extension → language name)
# ---------------------------------------------------------------------------

_EXT_TO_LANGUAGE: dict[str, str] = {
    # Python
    ".py": "Python", ".pyw": "Python", ".pyi": "Python",
    # JavaScript / TypeScript
    ".js": "JavaScript", ".mjs": "JavaScript", ".cjs": "JavaScript",
    ".jsx": "JavaScript",
    ".ts": "TypeScript", ".tsx": "TypeScript", ".mts": "TypeScript",
    # Web
    ".html": "HTML", ".htm": "HTML",
    ".css": "CSS", ".scss": "SCSS", ".sass": "SASS", ".less": "LESS",
    # Data / config
    ".json": "JSON", ".jsonc": "JSON",
    ".yaml": "YAML", ".yml": "YAML",
    ".toml": "TOML", ".ini": "INI", ".cfg": "INI", ".conf": "INI",
    ".env": "ENV",
    # Shell
    ".sh": "Shell", ".bash": "Shell", ".zsh": "Shell", ".fish": "Shell",
    ".ps1": "PowerShell", ".psm1": "PowerShell",
    ".bat": "Batch", ".cmd": "Batch",
    # Systems / compiled
    ".c": "C", ".h": "C",
    ".cpp": "C++", ".cc": "C++", ".cxx": "C++", ".hpp": "C++", ".hxx": "C++",
    ".cs": "C#",
    ".java": "Java",
    ".kt": "Kotlin", ".kts": "Kotlin",
    ".go": "Go",
    ".rs": "Rust",
    ".swift": "Swift",
    ".rb": "Ruby",
    ".php": "PHP",
    # Data science
    ".r": "R", ".R": "R",
    ".jl": "Julia",
    # SQL
    ".sql": "SQL",
    # Markup / docs
    ".md": "Markdown", ".mdx": "Markdown",
    ".rst": "reStructuredText",
    ".tex": "LaTeX",
    ".xml": "XML", ".xsd": "XML", ".xsl": "XML",
    # Infrastructure / containers
    ".tf": "Terraform", ".tfvars": "Terraform",
    ".dockerfile": "Dockerfile",
    # Other
    ".graphql": "GraphQL", ".gql": "GraphQL",
    ".proto": "Protobuf",
    ".lua": "Lua",
    ".vim": "Vim Script",
}

#: Exact filenames that map to a language (e.g. "Dockerfile" has no extension).
_FILENAME_TO_LANGUAGE: dict[str, str] = {
    "Dockerfile": "Dockerfile",
    "Makefile": "Makefile",
    "Rakefile": "Ruby",
    "Gemfile": "Ruby",
    "Vagrantfile": "Ruby",
    "Jenkinsfile": "Groovy",
    ".gitignore": "GitIgnore",
    ".gitattributes": "GitAttributes",
    ".editorconfig": "EditorConfig",
}

# ---------------------------------------------------------------------------
# Generated-file detection
# ---------------------------------------------------------------------------

#: Exact filenames always considered auto-generated.
_GENERATED_FILENAMES: frozenset[str] = frozenset(
    {
        "package-lock.json",
        "yarn.lock",
        "pnpm-lock.yaml",
        "Pipfile.lock",
        "poetry.lock",
        "Cargo.lock",
        "composer.lock",
        "Gemfile.lock",
        "go.sum",
        "npm-shrinkwrap.json",
    }
)

#: Suffixes indicating minified or bundled output.
_GENERATED_SUFFIXES: tuple[str, ...] = (
    ".min.js",
    ".min.css",
    ".bundle.js",
    ".bundle.css",
    ".chunk.js",
    ".map",      # source maps
)

#: Phrases checked only in the first 3 lines of a file to detect auto-generated files.
#: Kept intentionally specific to avoid false positives on normal source comments.
_GENERATED_HEADERS: tuple[str, ...] = (
    "this file is auto-generated",
    "@generated",
    "code generated by",
    "this code was generated",
    "do not edit this file",
    "do not modify this file",
    "auto-generated by",
)


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------

class FileClassifier:
    """Classifies a file path into a fully-populated FileInfo."""

    def classify(self, path: Path) -> FileInfo:
        """
        Return a FileInfo for *path*.

        The method never raises: any IO error produces a conservative result
        (is_binary=True so the file is skipped by downstream analysis).
        """
        try:
            size_bytes = path.stat().st_size
        except OSError as exc:
            log.warning("Cannot stat %s: %s", path, exc)
            return FileInfo(path=path, size_bytes=0, is_binary=True)

        language = self._detect_language(path)
        is_generated = self._is_generated(path)

        # Oversized: flag and skip reading
        if size_bytes > MAX_FILE_SIZE_BYTES:
            return FileInfo(
                path=path,
                language=language,
                size_bytes=size_bytes,
                is_generated=is_generated,
                is_oversized=True,
            )

        # Binary probe
        if self._is_binary(path):
            return FileInfo(
                path=path,
                language=language,
                size_bytes=size_bytes,
                is_binary=True,
                is_generated=is_generated,
            )

        # Normal text file — count lines
        line_count = self._count_lines(path)
        return FileInfo(
            path=path,
            language=language,
            size_bytes=size_bytes,
            line_count=line_count,
            is_generated=is_generated,
        )

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _detect_language(path: Path) -> str | None:
        # Exact filename match first (e.g. Dockerfile)
        if path.name in _FILENAME_TO_LANGUAGE:
            return _FILENAME_TO_LANGUAGE[path.name]
        # Extension match — handle compound extensions like .min.js
        name_lower = path.name.lower()
        for suffix in _GENERATED_SUFFIXES:
            if name_lower.endswith(suffix):
                # Still try to resolve the base language
                base_ext = Path(name_lower.removesuffix(suffix)).suffix
                return _EXT_TO_LANGUAGE.get(base_ext)
        return _EXT_TO_LANGUAGE.get(path.suffix.lower())

    @staticmethod
    def _is_generated(path: Path) -> bool:
        if path.name in _GENERATED_FILENAMES:
            return True
        name_lower = path.name.lower()
        if any(name_lower.endswith(s) for s in _GENERATED_SUFFIXES):
            return True
        # Header check — inspect only the first 3 lines to avoid false positives
        # from normal source files that have comment sections mentioning "do not"
        # or similar phrases deep in the file body.
        try:
            raw = path.read_bytes()[:1024].decode("utf-8", errors="replace")
            first_lines = "\n".join(raw.splitlines()[:3]).lower()
            return any(marker in first_lines for marker in _GENERATED_HEADERS)
        except OSError:
            return False

    @staticmethod
    def _is_binary(path: Path) -> bool:
        try:
            chunk = path.read_bytes()[:_BINARY_PROBE_BYTES]
            return b"\x00" in chunk
        except OSError:
            return True  # conservative: treat unreadable as binary

    @staticmethod
    def _count_lines(path: Path) -> int | None:
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
            return text.count("\n") + (1 if text and not text.endswith("\n") else 0)
        except OSError:
            return None
